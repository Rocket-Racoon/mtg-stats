"""Acceptance tests for S-1.4.3 (Alembic migrations and drift check).

Every test runs Alembic against its own throwaway database (see ``migration_support``), never
against ``mtg_stats`` or ``mtg_stats_test``. The tests are synchronous because ``env.py`` runs
its own event loop with ``asyncio.run``.
"""

import os
import re
import subprocess
import sys
from pathlib import Path

import pytest
from alembic import command
from alembic.util.exc import CommandError
from sqlalchemy import Column, Index, Integer, MetaData, String, Table, create_engine, inspect
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

import app.model_registry as registry
from app.core.config import DATABASE_URL_PREFIX
from app.core.db import NAMING_CONVENTION, Base, IdMixin, TimestampMixin
from tests.migration_support import (
    ALEMBIC_INI,
    API_ROOT,
    MIGRATION_FILE_RE,
    alembic_config,
    temporary_database,
)

REAL_VERSIONS = API_ROOT / "migrations" / "versions"
LONG_TABLE = "sample_extraordinarily_long_table_name_for_identifier_limits"
LONG_COLUMNS = ("first_long_column_name", "second_long_column_name")


class _Meta(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class _Item(IdMixin, TimestampMixin, _Meta):
    __tablename__ = "mig_items"
    name: Mapped[str] = mapped_column(String(50), default="")


class _LongNamed(IdMixin, _Meta):
    """Index and unique names generated by the convention exceed Postgres' 63 characters."""

    __tablename__ = LONG_TABLE
    __table_args__ = (Index(None, *LONG_COLUMNS),)
    first_long_column_name: Mapped[str] = mapped_column(String(10), default="")
    second_long_column_name: Mapped[str] = mapped_column(String(10), default="")


def _metadata_with_drift() -> MetaData:
    """Same models as ``_Meta`` plus one extra table, as if a model changed without a migration."""
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    for table in _Meta.metadata.tables.values():
        table.to_metadata(metadata)

    Table("mig_extra", metadata, Column("id", Integer, primary_key=True))
    return metadata


def _table_names(url: str) -> set[str]:
    engine = create_engine(url)
    try:
        return set(inspect(engine).get_table_names())
    finally:
        engine.dispose()


def test_upgrade_downgrade_upgrade_round_trip_succeeds(monkeypatch: pytest.MonkeyPatch) -> None:
    with temporary_database(monkeypatch) as url:
        config = alembic_config()
        command.upgrade(config, "head")
        assert "alembic_version" in _table_names(url)
        command.downgrade(config, "base")
        command.upgrade(config, "head")
        command.check(config)


def test_cli_check_exits_zero_when_models_and_migrations_are_in_sync(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    with temporary_database(monkeypatch) as url:
        env = {**os.environ, "APP_ENV": "test", "DATABASE_URL": url}
        for args in (["upgrade", "head"], ["check"]):
            result = subprocess.run(  # noqa: S603
                [sys.executable, "-m", "alembic", *args],
                cwd=API_ROOT,
                env=env,
                capture_output=True,
                text=True,
                timeout=120,
                check=False,
            )
            assert result.returncode == 0, result.stderr


def test_check_fails_when_a_model_changes_without_a_migration(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    with temporary_database(monkeypatch):
        config = alembic_config(tmp_path, target_metadata=_Meta.metadata)
        command.revision(config, message="models", autogenerate=True)
        command.upgrade(config, "head")
        command.check(config)

        drifted = alembic_config(tmp_path, target_metadata=_metadata_with_drift())
        with pytest.raises(CommandError, match="New upgrade operations detected"):
            command.check(drifted)


def test_env_reads_url_from_settings_and_loads_models_from_the_registry() -> None:
    ini = ALEMBIC_INI.read_text(encoding="utf-8")
    env_py = (API_ROOT / "migrations" / "env.py").read_text(encoding="utf-8")
    assert not re.search(r"^\s*sqlalchemy\.url", ini, re.MULTILINE)
    assert "get_settings().database_url" in env_py
    assert "from app.model_registry import" in env_py
    assert registry.metadata is Base.metadata


def test_env_uses_the_async_psycopg_engine_from_settings() -> None:
    env_py = (API_ROOT / "migrations" / "env.py").read_text(encoding="utf-8")
    assert "create_async_engine(get_settings().database_url" in env_py
    assert DATABASE_URL_PREFIX == "postgresql+psycopg://"


def test_generated_migration_file_name_follows_the_template(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    with temporary_database(monkeypatch):
        config = alembic_config(tmp_path, target_metadata=_Meta.metadata)
        command.revision(config, message="Add Some Things", autogenerate=True)
    names = [path.name for path in tmp_path.glob("*.py")]
    assert len(names) == 1
    assert MIGRATION_FILE_RE.match(names[0]), names[0]
    assert names[0].endswith("_add_some_things.py")
    for path in REAL_VERSIONS.glob("*.py"):
        assert MIGRATION_FILE_RE.match(path.name), path.name


def test_long_generated_constraint_names_are_stable_across_autogenerate_and_check(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    with temporary_database(monkeypatch) as url:
        config = alembic_config(tmp_path, target_metadata=_Meta.metadata)
        command.revision(config, message="models", autogenerate=True)
        command.upgrade(config, "head")
        command.check(config)

        # A second autogenerate finds nothing to do, so its revision has no operations.
        command.revision(config, message="again", autogenerate=True)
        generated = list(tmp_path.glob("*.py"))
        assert len(generated) == 2
        again = next(path for path in generated if path.name.endswith("_again.py"))
        body = again.read_text(encoding="utf-8")
        upgrade_body = body.split("def upgrade() -> None:")[1].split("def downgrade")[0]
        assert "op." not in upgrade_body
        again.unlink()

        engine = create_engine(url)
        try:
            names = {ix["name"] for ix in inspect(engine).get_indexes(LONG_TABLE)}
            pk = inspect(engine).get_pk_constraint(LONG_TABLE)["name"]
        finally:
            engine.dispose()
    long_index = next(iter(names))
    assert len(long_index) <= 63
    assert long_index.startswith("ix_sample_extraordinarily_long")
    assert len(pk) <= 63
    unrendered = f"ix_{LONG_TABLE}_{'_'.join(LONG_COLUMNS)}"
    assert len(unrendered) > 63
