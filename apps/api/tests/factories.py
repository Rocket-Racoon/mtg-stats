class PrintingFactory(BaseFactory):
    """A printing. Persist its card first and pass ``oracle_id=card.oracle_id``."""

    class Meta:
        model = Printing

    id = factory.LazyFunction(uuid4)
    oracle_id = factory.LazyFunction(uuid4)
    set_code = "tst"
    set_name = "Test Set"
    collector_number = factory.Sequence(lambda n: str(n + 1))
    rarity = "common"
    lang = "en"
    released_at = date(2024, 1, 1)
    finishes = factory.LazyFunction(lambda: ["nonfoil", "foil"])
    image_uris = factory.LazyFunction(
        lambda: {"normal": "https://cards.scryfall.io/normal/test.jpg"}
    )
    digital = False
    oversized = False
    updated_at = factory.LazyFunction(lambda: datetime.now(UTC))


class DoubleFacedPrintingFactory(PrintingFactory):
    """A printing of a double-faced card: image URIs are kept per face."""

    image_uris = factory.LazyFunction(
        lambda: {
            "faces": [
                {"normal": "https://cards.scryfall.io/normal/front.jpg"},
                {"normal": "https://cards.scryfall.io/normal/back.jpg"},
            ]
        }
    )


def _as_uuid(value: object) -> UUID:
    assert isinstance(value, UUID)
    return value
