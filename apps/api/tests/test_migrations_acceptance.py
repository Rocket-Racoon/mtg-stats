def test_cli_ignores_a_bogus_sqlalchemy_url_in_the_ini_and_uses_the_settings_url(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    with temporary_database(monkeypatch) as url:
        ini = tmp_path / "alembic.ini"
        text_ini = ALEMBIC_INI.read_text(encoding="utf-8").replace(
            "%(here)s/migrations", (API_ROOT / "migrations").as_posix()
        )
        ini.write_text(
            text_ini.replace(
                "[alembic]\n",
                "[alembic]\nsqlalchemy.url = postgresql+psycopg://nobody@127.0.0.1:1/bogus\n",
                1,
            ),
            encoding="utf-8",
        )
        assert "bogus" in ini.read_text(encoding="utf-8")
        result = _cli(url, "upgrade", "head", ini=ini)
        assert result.returncode == 0, result.stderr
        head = ScriptDirectory.from_config(alembic_config()).get_current_head()
        assert _versions(url) == [head]


def _models_modules(app_dir: Path) -> set[str]:
    """Dotted names of every ``<app_dir>/<domain>/models.py`` or ``models/__init__.py``."""
    pkg = app_dir.name
    return {f"{pkg}.{path.parent.name}.models" for path in app_dir.glob("*/models.py")} | {
        f"{pkg}.{path.parent.parent.name}.models" for path in app_dir.glob("*/models/__init__.py")
    }


def _registry_imports(registry_file: Path) -> set[str]:
    """Modules the registry imports: ``import a.b``, ``from a import b``, ``from a.b import c``."""
    imported: set[str] = set()
    for node in ast.walk(ast.parse(registry_file.read_text(encoding="utf-8"))):
        if isinstance(node, ast.Import):
            imported |= {alias.name for alias in node.names}
        elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
            imported.add(node.module)
            imported |= {f"{node.module}.{alias.name}" for alias in node.names}
    return imported


def _unregistered_models(app_dir: Path, registry_file: Path) -> set[str]:
    imported = _registry_imports(registry_file)
    return {
        module
        for module in _models_modules(app_dir)
        if not any(name == module or name.startswith(f"{module}.") for name in imported)
    }


def test_registry_imports_every_domains_models_module() -> None:
    assert _unregistered_models(API_ROOT / "app", API_ROOT / "app" / "model_registry.py") == set()


def test_registry_guard_reports_a_domain_whose_models_are_not_imported(tmp_path: Path) -> None:
    app_dir = tmp_path / "app"
    (app_dir / "alpha").mkdir(parents=True)
    (app_dir / "alpha" / "models.py").write_text("", encoding="utf-8")
    (app_dir / "beta" / "models").mkdir(parents=True)
    (app_dir / "beta" / "models" / "__init__.py").write_text("", encoding="utf-8")
    (app_dir / "gamma").mkdir()  # no models module: not a domain with tables
    registry_file = app_dir / "model_registry.py"

    assert _models_modules(app_dir) == {"app.alpha.models", "app.beta.models"}

    registry_file.write_text("import app.alpha.models\n", encoding="utf-8")
    assert _unregistered_models(app_dir, registry_file) == {"app.beta.models"}

    registry_file.write_text(
        "import app.alpha.models\nfrom app.beta import models\n", encoding="utf-8"
    )
    assert _unregistered_models(app_dir, registry_file) == set()

    registry_file.write_text("from app.beta.models import Thing\n", encoding="utf-8")
    assert _unregistered_models(app_dir, registry_file) == {"app.alpha.models"}


