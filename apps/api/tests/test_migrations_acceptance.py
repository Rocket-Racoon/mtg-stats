# ------------------------------------------------------------------ AC6: long names


def test_long_generated_constraint_names_are_stable_across_autogenerate_and_check(
    meta_db: MetaDb,
) -> None:
    command.check(meta_db.config())
    # A second autogenerate finds nothing to do, so its revision has no operations.
    command.revision(meta_db.config(), message="again", autogenerate=True)
    again = next(meta_db.versions_dir.glob("*_again.py"))
    try:
        body = again.read_text(encoding="utf-8")
    finally:
        again.unlink()
    upgrade_body = body.split("def upgrade() -> None:")[1].split("def downgrade")[0]
    assert "op." not in upgrade_body

    engine = create_engine(meta_db.url)
    try:
        names = {ix["name"] for ix in inspect(engine).get_indexes(LONG_TABLE)}
        pk = inspect(engine).get_pk_constraint(LONG_TABLE)["name"]
    finally:
        engine.dispose()
    long_index = next(iter(names))
    assert long_index is not None
    assert pk is not None
    assert len(long_index) <= 63
    assert long_index.startswith("ix_sample_extraordinarily_long")
    assert len(pk) <= 63
    unrendered = f"ix_{LONG_TABLE}_{'_'.join(LONG_COLUMNS)}"
    assert len(unrendered) > 63


def test_long_constraint_names_follow_the_naming_convention_prefixes(meta_db: MetaDb) -> None:
    engine = create_engine(meta_db.url)
    try:
        insp = inspect(engine)
        table = LONG_CONSTRAINED_TABLE
        fk = insp.get_foreign_keys(table)[0]["name"]
        uq = insp.get_unique_constraints(table)[0]["name"]
        pk = insp.get_pk_constraint(table)["name"]
        ix = insp.get_indexes(LONG_TABLE)[0]["name"]
    finally:
        engine.dispose()
    assert fk is not None
    assert uq is not None
    assert pk is not None
    assert ix is not None
    assert len(f"fk_{table}_item_reference_identifier_mig_items") > 63
    assert len(f"uq_{table}_{'_'.join(LONG_COLUMNS)}") > 63
    for name, prefix in ((fk, "fk_"), (uq, "uq_"), (pk, "pk_"), (ix, "ix_")):
        assert name.startswith(prefix), name
        assert len(name) <= 63, name
    assert fk.startswith("fk_sample_long_constrained")
    assert uq.startswith("uq_sample_long_constrained")
    assert pk == f"pk_{table}"
