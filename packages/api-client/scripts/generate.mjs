// Generates src/generated/schema.d.ts from openapi.json with openapi-typescript.
//
//   node scripts/generate.mjs [--input <openapi.json>] [--output <schema.d.ts>] [--check]
//
// --check writes nothing and exits 1 when the output file differs from a fresh generation: a
// quick TS-only consistency check of the schema against the committed spec. The end-to-end
// drift gate (API code -> spec -> schema) is `pnpm client:check`.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function parseArgs(argv) {
  const opts = {
    input: resolve(root, 'openapi.json'),
    output: resolve(root, 'src/generated/schema.d.ts'),
    check: false,
  };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--check') opts.check = true;
    else if (arg === '--input' || arg === '--output') {
      const value = argv[++i];
      if (!value) throw new Error(`${arg} needs a value`);
      opts[arg.slice(2)] = resolve(process.cwd(), value);
    } else throw new Error(`Unknown argument: ${arg}`);
  }
  return opts;
}

const HEADER = '// Generated by scripts/generate.mjs from openapi.json. Do not edit by hand.\n';

const { input, output, check } = parseArgs(process.argv.slice(2));
const ast = await openapiTS(pathToFileURL(input), { alphabetize: true });
const generated = HEADER + astToString(ast).replace(/\r\n/g, '\n');

if (check) {
  const current = existsSync(output) ? readFileSync(output, 'utf8').replace(/\r\n/g, '\n') : null;
  if (current !== generated) {
    console.error(
      `${output} is out of date. Run \`pnpm --filter @mtg-stats/api-client generate\` and commit the result.`,
    );
    process.exit(1);
  }
  console.log('api-client schema is up to date.');
} else {
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, generated, { encoding: 'utf8' });
  console.log(`Wrote ${output}`);
}
