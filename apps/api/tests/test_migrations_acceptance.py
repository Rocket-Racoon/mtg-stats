REAL_VERSIONS = API_ROOT / "migrations" / "versions"
LONG_TABLE = "sample_extraordinarily_long_table_name_for_identifier_limits"
LONG_CONSTRAINED_TABLE = "sample_long_constrained_table_for_fk_and_unique_limits"
LONG_COLUMNS = ("first_long_column_name", "second_long_column_name")


class _Meta(Base):
    """Separate metadata (like ``SampleBase``) so test tables never reach the real schema."""

    __abstract__ = True
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class _Item(IdMixin, TimestampMixin, _Meta):
    __tablename__ = "mig_items"
    name: Mapped[str] = mapped_column(String(50), default="")


class _LongNamed(IdMixin, _Meta):
    """Index and unique names generated by the convention exceed Postgres' 63 characters."""

    __tablename__ = LONG_TABLE
    __table_args__ = (Index(None, *LONG_COLUMNS),)
    first_long_column_name: Mapped[str] = mapped_column(String(10), default="")
    second_long_column_name: Mapped[str] = mapped_column(String(10), default="")


class _LongConstrained(IdMixin, _Meta):
    """Generated FK and unique names for this table also exceed Postgres' 63 characters."""

    __tablename__ = LONG_CONSTRAINED_TABLE
    __table_args__ = (UniqueConstraint(*LONG_COLUMNS),)
    first_long_column_name: Mapped[str] = mapped_column(String(10), default="")
    second_long_column_name: Mapped[str] = mapped_column(String(10), default="")
    item_reference_identifier: Mapped[UUID | None] = mapped_column(
        PG_UUID(as_uuid=True), ForeignKey("mig_items.id")
    )


def _metadata_with_drift() -> MetaData:
    """Same models as ``_Meta`` plus one extra table, as if a model changed without a migration."""
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    for table in _Meta.metadata.tables.values():
        table.to_metadata(metadata)

    Table("mig_extra", metadata, Column("id", Integer, primary_key=True))
    return metadata


def _table_names(url: str) -> set[str]:
    engine = create_engine(url)
    try:
        return set(inspect(engine).get_table_names())
    finally:
        engine.dispose()


def _versions(url: str) -> list[str]:
    engine = create_engine(url)
    try:
        with engine.connect() as conn:
            return [row[0] for row in conn.execute(text("SELECT version_num FROM alembic_version"))]
    finally:
        engine.dispose()


def _cli(url: str, *args: str, ini: Path | None = None) -> subprocess.CompletedProcess[str]:
    """Run the real ``python -m alembic`` CLI; DATABASE_URL is the only URL it is given."""
    env = {**os.environ, "APP_ENV": "test", "DATABASE_URL": url}
    argv = [sys.executable, "-m", "alembic"]
    if ini is not None:
        argv += ["-c", str(ini)]
    return subprocess.run(  # noqa: S603
        [*argv, *args],
        cwd=API_ROOT,
        env=env,
        capture_output=True,
        text=True,
        timeout=300,
        check=False,
    )


@dataclass(frozen=True)
class MetaDb:
    """A throwaway database already migrated to the ``_Meta`` models, plus its versions dir."""

    url: str
    versions_dir: Path

    def config(self, **attributes: object) -> Config:
        return alembic_config(self.versions_dir, target_metadata=_Meta.metadata, **attributes)


@pytest.fixture(scope="module")
def _meta_schema(tmp_path_factory: pytest.TempPathFactory) -> Iterator[MetaDb]:
    """One database and one autogenerated revision shared by the ``_Meta`` tests."""
    versions_dir = tmp_path_factory.mktemp("meta_versions")
    with pytest.MonkeyPatch.context() as mp, temporary_database(mp) as url:
        meta = MetaDb(url, versions_dir)
        command.revision(meta.config(), message="models", autogenerate=True)
        command.upgrade(meta.config(), "head")
        command.check(meta.config())
        yield meta


@pytest.fixture
def meta_db(_meta_schema: MetaDb, monkeypatch: pytest.MonkeyPatch) -> MetaDb:
    monkeypatch.setenv("APP_ENV", "test")
    monkeypatch.setenv("DATABASE_URL", _meta_schema.url)
    get_settings.cache_clear()
    return _meta_schema


# ------------------------------------------------------------------ AC1: round trip


def test_upgrade_downgrade_upgrade_round_trip_succeeds(monkeypatch: pytest.MonkeyPatch) -> None:
    with temporary_database(monkeypatch) as url:
        config = alembic_config()
        command.upgrade(config, "head")
        assert "alembic_version" in _table_names(url)
        command.downgrade(config, "base")
        assert _versions(url) == []  # downgrade to base clears the version table
        command.upgrade(config, "head")
        command.check(config)
        head = ScriptDirectory.from_config(config).get_current_head()
        assert head is not None
        assert _versions(url) == [head]


# ------------------------------------------------------------------ AC2: check


def test_cli_check_exits_zero_in_sync_and_non_zero_after_drift(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Drift through the real CLI: the DB holds a table the registry's models do not define."""
    with temporary_database(monkeypatch) as url:
        assert _cli(url, "upgrade", "head").returncode == 0
        in_sync = _cli(url, "check")
        assert in_sync.returncode == 0, in_sync.stderr
        engine = create_engine(url)
        try:
            with engine.begin() as conn:
                conn.execute(text("CREATE TABLE drifted_table (id integer PRIMARY KEY)"))
        finally:
            engine.dispose()
        result = _cli(url, "check")
        assert result.returncode != 0
        assert "New upgrade operations detected" in result.stderr + result.stdout


def test_check_fails_when_a_model_changes_without_a_migration(meta_db: MetaDb) -> None:
    command.check(meta_db.config())
    drifted = alembic_config(meta_db.versions_dir, target_metadata=_metadata_with_drift())
    with pytest.raises(CommandError, match="New upgrade operations detected"):
        command.check(drifted)


