def test_generated_migration_file_name_follows_the_template(tmp_path: Path) -> None:
    """A plain (non-autogenerate) revision does not run env.py, so it needs no database."""
    command.revision(alembic_config(tmp_path), message="Add Some Things", autogenerate=False)
